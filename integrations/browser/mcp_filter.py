"""Stdio allowlist filter between `claude` and the pinned playwright-mcp (docs/BROWSER-TOOL.md, ticket B1b).

    python3 -I mcp_filter.py --task <task_dir> [--browsers-path <prefix>/browsers] [--grant browser_js]
        [--grant browser_upload] [--max-pages N]
        [--tools-file F] [--args-file F] [--client-line-max N] [--server-line-max N] -- <server command...>          (normally: run-mcp.sh <task_dir> <prefix>)

The filter starts the server as a child over pipes and is the only thing Claude Code talks to. It is the server-side
tool boundary that holds even if Claude Code's --disallowedTools is misconfigured, so everything fails closed:
- tools/list answers are rewritten to the allowed names; a tools/call for any other name is refused, never forwarded;
- tools/call arguments may only use the tool's keys from the pinned schemas (args-0.0.84.json), and never `filename`;
- upload/drop paths must be absolute and resolve under <task>/browser/in;
- browser_navigate / browser_tabs URLs must be http:, https: or exactly about:blank (item 7c: javascript:/data:
  navigations run script exactly as the denied browser_evaluate would);
- pages opened through the filter (navigate, navigate_back, new tab) are counted and refused past the cap;
- only the listed client methods pass; batches, bad JSON, non-objects and oversize lines close the session;
- server->client requests (roots/list, sampling/*, elicitation/*, any other) are answered here with an error and never
  reach the client (item 7d: roots would widen the server's file boundary to the child's repo).
Stdlib only. Refusals are JSON-RPC errors with fixed reason text; nothing from a refused request is echoed back.
"""
import argparse
import ctypes
import json
import os
import re
import signal
import subprocess
import sys
import threading
import time
from urllib.parse import urlsplit

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS_FILE = os.path.join(HERE, "tools-0.0.84.txt")
# Per-tool argument keys from the pinned server's inputSchema.properties (generated by `install.sh args`, diffed by the
# install gate). A key outside a tool's set is refused, so a new path/URL argument can never pass unchecked.
ARGS_FILE = os.path.join(HERE, "args-0.0.84.json")
# Refused on every tool: `filename` (snapshot, console_messages, find, network_request(s), take_screenshot, evaluate)
# is a local write path resolved by the server against its workspace, page-controlled bytes included. Bounding it
# would rely on the server's own checkFile; without it the server auto-names outputs under --output-dir.
REFUSED_KEYS = frozenset({"filename"})

# Default-off tools (items 5, 6): page JS, host code execution, local-file posting. Grants add some back.
DEFAULT_OFF = frozenset({"browser_evaluate", "browser_run_code_unsafe", "browser_file_upload", "browser_drop"})
GRANTS = {"browser_js": frozenset({"browser_evaluate"}),
          "browser_upload": frozenset({"browser_file_upload", "browser_drop"})}
# Host code execution (vm.runInContext in the server process): never grantable, whatever the configuration says.
NEVER = frozenset({"browser_run_code_unsafe"})
UPLOAD_TOOLS = frozenset({"browser_file_upload", "browser_drop"})
# The local-path key of the upload/drop tools in the pinned schemas ({paths} and {element, target, paths, data});
# every entry must be absolute and resolve under <task>/browser/in. Other keys are refused by the args allowlist.
PATH_KEYS = ("paths",)
PAGE_TOOLS = frozenset({"browser_navigate", "browser_navigate_back"})

CLIENT_METHODS = frozenset({"initialize", "notifications/initialized", "ping", "tools/list", "tools/call",
                            "notifications/cancelled"})
# Server notifications the client may see; everything else (resources/prompts changes, ...) is dropped.
SERVER_NOTIFICATIONS = frozenset({"notifications/progress", "notifications/message",
                                  "notifications/tools/list_changed"})

# Default page cap (docs "Caps": browser_max_pages default 50): bounds how much a child can browse per task.
DEFAULT_MAX_PAGES = 50
# Client lines are tool calls with small arguments (URLs, form text); 1 MiB is far above any real one and keeps a
# runaway client from making the filter buffer without bound.
CLIENT_LINE_MAX = 1 << 20
# Server lines carry base64 screenshots in tool results (a full-page PNG can be several MB); 64 MiB bounds memory while
# leaving room for those. Peak memory per line is ~3-4x the cap (bytes, parsed objects, re-serialised output).
SERVER_LINE_MAX = 64 << 20
# Grace for the server to exit (after stdin EOF, and again after SIGTERM) before it is killed: long enough for a clean
# browser shutdown (Playwright's signal handlers kill the browser it launched), short enough that a hung server never
# outlives the child session for long.
EXIT_GRACE_S = 5
# Absolute, so a PATH entry cannot substitute the process lister the kill walk trusts.
PS = "/bin/ps"
# ps runs in the C locale so `lstart` is always five whitespace-separated fields ("Tue Nov  3 20:12:42 2026").
PS_ENV = {"LC_ALL": "C", "PATH": "/usr/bin:/bin"}
# Kernel process identity on macOS (libproc's proc_pidpath and sysctl KERN_PROCARGS2), via ctypes: ps prints argv,
# which a process writes itself, so an executable path read from ps text proves nothing. Off macOS (or if either call is
# unavailable) the identity is unknown and nothing is killed by command line.
LIBPROC = "/usr/lib/libproc.dylib"
PROC_PIDPATHINFO_MAXSIZE = 4096
CTL_KERN, KERN_PROCARGS2 = 1, 49
# Executable names of the browsers Playwright installs under PLAYWRIGHT_BROWSERS_PATH (Chromium, Chrome for Testing, the
# headless shell, old and new layouts) and their macOS helper apps ("Chromium Helper (Renderer)"). Ownership by command
# line accepts only these, so a shell or any other program whose argv mentions the task dir is never killed.
BROWSER_EXE = re.compile(r"(headless_shell|chrome-headless-shell|chrome|Chromium|Google Chrome for Testing)"
                         r"( Helper( \([A-Za-z ]+\))?)?\Z")
# The filter's own request ids (re-list after list_changed) carry this prefix; client ids with it are refused so the
# two can never collide.
OWN_ID_PREFIX = "cortados-filter-"
# Descendants are sampled this often while the session runs, so a server that exits abruptly (its detached children
# reparented and no longer reachable by the walk) still leaves a recent tree behind for close(). 2 s keeps the cost to
# one ps per 2 s while bounding the window in which a newly launched child is known only by its command line.
TREE_POLL_S = 2

# Fixed refusal reasons (never echo request content back).
E_METHOD = (-32601, "method not allowed by the CortadOS browser filter")
E_PARAMS = (-32602, "invalid tools/call params refused by the CortadOS browser filter")
E_TOOL = (-32001, "tool not allowed by the CortadOS browser filter")
E_URL = (-32002, "URL refused by the CortadOS browser filter: only http:, https: and about:blank")
E_PAGES = (-32003, "page cap reached: the CortadOS browser filter refuses further navigation")
E_PATH = (-32004, "path refused by the CortadOS browser filter: upload paths must be under <task>/browser/in")
E_ID = (-32600, "invalid request id refused by the CortadOS browser filter")
E_ARG = (-32005, "argument key not allowed by the CortadOS browser filter")
E_FILENAME = (-32004, "filename refused by the CortadOS browser filter: outputs are auto-named under the output dir")
E_SERVER_REQ = (-32601, "server-to-client requests are not supported by the CortadOS browser filter")
E_LIST = (-32603, "malformed tools/list answer from the browser server")


def pinned_tools(path=TOOLS_FILE):
    with open(path) as f:
        names = f.read().split()
    if not names:
        raise SystemExit(f"mcp_filter: {path} is empty; refusing to run without a pinned tool list")
    return frozenset(names)


def pinned_args(pinned, path=ARGS_FILE):
    """{tool: frozenset(keys)}; every pinned tool must have an entry (fail closed: a tool with no reviewed key set is
    not callable with guessed keys)."""
    with open(path) as f:
        raw = json.load(f)
    if not isinstance(raw, dict) or not all(isinstance(v, list) and all(isinstance(k, str) for k in v)
                                            for v in raw.values()):
        raise SystemExit(f"mcp_filter: {path} is not a {{tool: [keys]}} object")
    if set(raw) != set(pinned):
        raise SystemExit(f"mcp_filter: {path} tools differ from the pinned tool list; refusing to run")
    return {k: frozenset(v) for k, v in raw.items()}


def allowed_tools(pinned, grants):
    """Pinned list minus default-off, plus grants (only names the pinned server has), minus NEVER."""
    allowed = set(pinned) - DEFAULT_OFF
    for g in grants:
        if g not in GRANTS:
            raise SystemExit(f"mcp_filter: unknown grant {g!r}")
        allowed |= GRANTS[g] & pinned
    return frozenset(allowed - NEVER)


def url_ok(url):
    """Allowlist, not a deny list: exactly about:blank, or an http(s) URL with a host. The scheme must be lowercase and
    first (no leading whitespace or control characters: browsers strip those, so ' javascript:' or 'JavaScript:' would
    otherwise reach the page)."""
    if not isinstance(url, str):
        return False
    if url == "about:blank":
        return True
    if any(ord(c) <= 0x20 or ord(c) == 0x7f for c in url):
        return False
    if not (url.startswith("http://") or url.startswith("https://")):
        return False
    try:
        u = urlsplit(url)
        host = u.hostname
        u.port  # raises ValueError on a malformed port
    except ValueError:
        return False
    return u.scheme in ("http", "https") and bool(host)


class Filter:
    def __init__(self, server_cmd, task_dir, allowed, max_pages, args=None, out=None,
                 client_line_max=CLIENT_LINE_MAX, server_line_max=SERVER_LINE_MAX, browsers_path=None):
        self.allowed = allowed
        self.args = args if args is not None else pinned_args(allowed | NEVER | DEFAULT_OFF)
        self.client_line_max = client_line_max
        self.server_line_max = server_line_max
        self.max_pages = max_pages
        self.pages = 0
        self.in_dir = os.path.realpath(os.path.join(task_dir, "browser", "in"))
        self.out = out or sys.stdout.buffer
        self.out_lock = threading.Lock()
        self.srv_lock = threading.Lock()
        self.state_lock = threading.Lock()
        self.pending = {}          # forwarded client request id (json key) -> method
        self.own_seq = 0
        self.closer = None         # ident of the thread running close(); set once
        # {pid: lstart} of descendants seen while running (poll) or at stdin EOF, for kill_tree. The start time is kept
        # with the pid and re-checked before every signal, so a pid recycled after the process exited is never hit.
        self.known_tree = {}
        # Ownership that survives reparenting: run-mcp.sh points TMPDIR at <task>/browser/tmp and --isolated puts
        # Chromium's --user-data-dir under it. A process is this task's browser only if its executable is a Playwright
        # browser under the pinned PLAYWRIGHT_BROWSERS_PATH (passed as --browsers-path, the value run-mcp.sh sets) AND it
        # has a --user-data-dir= argument resolving inside <task>/browser/tmp. Without --browsers-path the match is off
        # (nothing is killed by command line): guessing the install location could only widen what gets killed.
        self.browsers_root = os.path.realpath(browsers_path) if browsers_path else None
        self.task_tmp = os.path.realpath(os.path.join(task_dir, "browser", "tmp"))
        # Self-pipe for SIGTERM/SIGHUP: the handler only writes a byte (no locks); a coordinator thread runs close().
        self.sig_r, self.sig_w = os.pipe()
        os.set_blocking(self.sig_w, False)
        # New session so close() can signal the server's group (wrapper, node). Not the browser: Playwright launches
        # Chromium detached, in a group of its own; close() finds it by walking descendants (kill_tree).
        self.proc = subprocess.Popen(server_cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                     start_new_session=True)
        # The server's start time, read while it is our unreaped child (its pid cannot be reused yet). descendants()
        # adopts children only of a process with this pid AND this start time; None (ps failed) disables the walk.
        self.server_start = self._start_of(self.proc.pid)
        if self.server_start is None:
            sys.stderr.write("mcp_filter: server start time unknown; descendant walk disabled\n")

    # output helpers
    def to_client(self, msg):
        data = json.dumps(msg, separators=(",", ":")).encode() + b"\n"
        with self.out_lock:
            self.out.write(data)
            self.out.flush()

    def to_server(self, msg):
        data = json.dumps(msg, separators=(",", ":")).encode() + b"\n"
        with self.srv_lock:
            self.proc.stdin.write(data)
            self.proc.stdin.flush()

    def error(self, mid, err, send=None):
        (send or self.to_client)({"jsonrpc": "2.0", "id": mid, "error": {"code": err[0], "message": err[1]}})

    def close(self, reason, code=1):
        with self.state_lock:
            closer, self.closer = self.closer, self.closer or threading.get_ident()
        if closer is not None:
            if closer == threading.get_ident():
                return   # re-entered on the closing thread: let that close finish
            # Another thread is closing: wait for its os._exit. Returning would let the main thread end the
            # interpreter and cut the other thread's kill_tree short, leaving the browser alive.
            threading.Event().wait()
        sys.stderr.write(f"mcp_filter: closing session: {reason}\n")
        sys.stderr.flush()
        self.kill_tree()
        os._exit(code)

    @staticmethod
    def _ps_full():
        """[(pid, pgid, ppid, uid, lstart, command)] of every process; [] if ps fails (reported, the group kill still
        ran). -ww: unlimited width, so a long Chromium command line is never truncated before its --user-data-dir."""
        try:
            r = subprocess.run([PS, "-ww", "-axo", "pid=,pgid=,ppid=,uid=,lstart=,command="], capture_output=True,
                               text=True, errors="replace", timeout=5, env=PS_ENV)
        except (OSError, subprocess.SubprocessError) as e:
            sys.stderr.write(f"mcp_filter: ps failed, descendants not walked: {e}\n")
            return []
        if r.returncode != 0:
            # subprocess.run does not raise on a failed exit: without this an empty list would silently skip cleanup.
            sys.stderr.write(f"mcp_filter: ps exited {r.returncode}, descendants not walked: {r.stderr.strip()[:500]}\n")
            return []
        rows = []
        for line in r.stdout.splitlines():
            parts = line.split(None, 9)
            if len(parts) >= 9 and all(p.isdigit() for p in parts[:4]):
                rows.append((*(int(p) for p in parts[:4]), " ".join(parts[4:9]), parts[9] if len(parts) == 10 else ""))
        return rows

    @staticmethod
    def _start_of(pid):
        """lstart of pid now, or None if it is gone (or ps fails: then nothing is signalled)."""
        try:
            out = subprocess.run([PS, "-o", "lstart=", "-p", str(pid)], capture_output=True, text=True,
                                 errors="replace", timeout=5, env=PS_ENV).stdout
        except (OSError, subprocess.SubprocessError) as e:
            sys.stderr.write(f"mcp_filter: ps failed, pid {pid} not signalled: {e}\n")
            return None
        return " ".join(out.split()) or None

    def _signal(self, pid, start, sig, group):
        """Send sig to pid (or the group it leads) only if pid still has the start time it was recorded with: a pid
        reused by an unrelated process since the sample is skipped. The ps-to-kill window left is one ps call."""
        if start is None or self._start_of(pid) != start:
            return False
        try:
            if group:
                os.killpg(pid, sig)
            else:
                os.kill(pid, sig)
        except (ProcessLookupError, PermissionError):
            return False  # exited since the check (EPERM: a zombie-only group on macOS)
        return True

    @staticmethod
    def _identity(pid):
        """(executable path, argv) of pid as the kernel reports them, or None if unknown (not macOS, call failed, process
        gone). The path is proc_pidpath's (the vnode actually executed, symlinks resolved), not argv[0]."""
        try:
            libproc = ctypes.CDLL(LIBPROC, use_errno=True)
            libc = ctypes.CDLL(None, use_errno=True)
            buf = ctypes.create_string_buffer(PROC_PIDPATHINFO_MAXSIZE)
            n = libproc.proc_pidpath(ctypes.c_int(pid), buf, ctypes.c_uint32(PROC_PIDPATHINFO_MAXSIZE))
            if n <= 0:
                return None
            exe = buf.raw[:n].decode("utf-8", "surrogateescape")
            mib = (ctypes.c_int * 3)(CTL_KERN, KERN_PROCARGS2, pid)
            size = ctypes.c_size_t(0)
            if libc.sysctl(mib, 3, None, ctypes.byref(size), None, ctypes.c_size_t(0)) != 0 or size.value < 4:
                return None
            raw = ctypes.create_string_buffer(size.value)
            if libc.sysctl(mib, 3, raw, ctypes.byref(size), None, ctypes.c_size_t(0)) != 0:
                return None
        except (OSError, AttributeError, ValueError):
            return None
        data = raw.raw[:size.value]
        # KERN_PROCARGS2: int32 argc, exec path NUL, NUL padding, then argc NUL-terminated argv strings.
        argc = int.from_bytes(data[:4], sys.byteorder)
        rest = data[4:]
        end = rest.find(b"\0")
        if end < 0:
            return None
        rest = rest[end:].lstrip(b"\0")
        argv = rest.split(b"\0")[:argc]
        if len(argv) != argc:
            return None
        return exe, [a.decode("utf-8", "surrogateescape") for a in argv]

    def is_task_browser(self, pid):
        """True if pid is a Playwright browser under the pinned browsers path running with a --user-data-dir inside
        <task>/browser/tmp, judged on the kernel's executable path and argv (_identity), never on ps text. The profile
        flag must be one whole argv entry. Unknown identity: False (fails safe: nothing is killed by command line)."""
        if self.browsers_root is None:
            return False
        ident = self._identity(pid)
        if ident is None:
            return False
        exe, argv = ident
        if not os.path.isabs(exe) or not BROWSER_EXE.match(os.path.basename(exe)):
            return False
        if not os.path.realpath(exe).startswith(self.browsers_root + os.sep):
            return False
        for tok in argv[1:]:
            if tok.startswith("--user-data-dir="):
                d = tok[len("--user-data-dir="):]
                if os.path.isabs(d) and os.path.realpath(d).startswith(self.task_tmp + os.sep):
                    return True
        return False

    def owned_by_task(self, rows=None):
        """{pid: (pgid, lstart)} of this user's processes that are this task's browser (is_task_browser). Never the
        filter itself or its parent (the child's claude), whatever their argv says."""
        me, parent, uid = os.getpid(), os.getppid(), os.getuid()
        found = {}
        for pid, pgid, _, puid, start, cmd in (self._ps_full() if rows is None else rows):
            if pid in (me, parent) or puid != uid:
                continue
            # The ps text is only a cheap pre-filter (no flag, no kernel lookup); the decision is is_task_browser's.
            if "--user-data-dir=" in cmd and self.is_task_browser(pid):
                found[pid] = (pgid, start)
        return found

    def descendants(self):
        """{pid: lstart} below the server process (Chromium included: its group differs, its parent chain does not).
        Empty unless this snapshot shows the server pid with the start time recorded at spawn: after the server is
        reaped its pid may belong to an unrelated process, whose children must never be adopted."""
        rows = self._ps_full()
        kids, starts = {}, {}
        for pid, _, ppid, _, start, _ in rows:
            kids.setdefault(ppid, []).append(pid)
            starts[pid] = start
        if self.server_start is None or starts.get(self.proc.pid) != self.server_start:
            return {}
        found, todo = {}, [self.proc.pid]
        while todo:
            for c in kids.get(todo.pop(), []):
                if c not in found:
                    found[c] = starts[c]
                    todo.append(c)
        return found

    def kill_tree(self):
        """SIGTERM the server's group, wait up to EXIT_GRACE_S, SIGKILL it; then SIGKILL every descendant (and the group
        it leads) still alive, and every process of this user that names the task's browser dir. The walk happens first:
        once node is gone its children are reparented and unreachable; the periodic poll (known_tree) and the
        command-line match cover a server that already exited on its own before close()."""
        with self.state_lock:
            tree = dict(self.known_tree)
        tree.update(self.descendants())
        self._kill_server_group(signal.SIGTERM)
        try:
            self.proc.wait(timeout=EXIT_GRACE_S)
        except subprocess.TimeoutExpired:
            sys.stderr.write("mcp_filter: server ignored SIGTERM; killing\n")
        self._kill_server_group(signal.SIGKILL)
        alive = {r[0]: r[1] for r in self._ps_full()}
        for pid, start in tree.items():
            if pid in alive:
                # A detached leader (Chromium) is killed with its group: its renderers share it. _signal re-checks the
                # recorded start time, so a recycled pid (and the group it may lead) is skipped.
                self._signal(pid, start, signal.SIGKILL, group=alive[pid] == pid)
        # Ownership by command line survives reparenting. Repeated (bounded) because a dying browser can still be
        # forking helpers between one ps and the kill.
        me_pgid = os.getpgid(0)
        for _ in range(3):
            owned = self.owned_by_task()
            if not owned:
                break
            for pid, (pgid, start) in owned.items():
                self._signal(pid, start, signal.SIGKILL, group=pgid == pid and pgid != me_pgid)
            time.sleep(0.1)

    def _kill_server_group(self, sig):
        """Signal the server's group only while the server is our unreaped child: until then its pid (and so the group
        id) cannot be reused. Once it is reaped the numeric group may be a replacement, so nothing is sent to it; the
        group's former members are recorded descendants, signalled one by one after their start time is verified."""
        if self.proc.poll() is not None:
            return
        try:
            os.killpg(self.proc.pid, sig)
        except (ProcessLookupError, PermissionError):
            # Gone, or (macOS) EPERM for a group left with only the unreaped server zombie: nothing to signal there;
            # descendants are handled by the caller.
            pass

    def poll_tree(self):
        """Record the server's descendants every TREE_POLL_S while it runs (see TREE_POLL_S)."""
        while self.closer is None and self.proc.poll() is None:
            tree = self.descendants()
            with self.state_lock:
                self.known_tree.update(tree)
            time.sleep(TREE_POLL_S)

    def on_signal(self, signum, frame):
        # Runs on the main thread between bytecodes, possibly while it holds state_lock: no locks, no close() here.
        # One byte to the self-pipe; the coordinator thread does the close.
        try:
            os.write(self.sig_w, bytes([signum & 0xff]))
        except OSError:
            pass  # pipe full: a byte is already waiting, which is all the coordinator needs

    def signal_loop(self):
        data = os.read(self.sig_r, 1)
        self.close(f"signal {data[0] if data else '?'}")

    # client -> server
    def on_client(self, msg):
        method = msg.get("method")
        if method is None:
            # A response from the client. The filter never forwards server requests, so there is nothing it may
            # answer; dropped.
            return
        is_request = "id" in msg
        mid = msg.get("id")
        if not isinstance(method, str) or method not in CLIENT_METHODS:
            if is_request:
                self.error(mid if self._id_ok(mid) else None, E_METHOD)
            return
        if not is_request:
            if method == "notifications/cancelled":
                # The client gave up on that request: forget it, so the id can be reused and the entry cannot leak.
                rid = (msg.get("params") or {}).get("requestId") if isinstance(msg.get("params"), dict) else None
                with self.state_lock:
                    self.pending.pop(json.dumps(rid), None)
            if method.startswith("notifications/"):
                self.to_server(msg)
            return
        if not self._id_ok(mid):
            self.error(None, E_ID)
            return
        if method == "tools/call":
            err = self.check_call(msg.get("params"), missing="params" not in msg)
            if err:
                self.error(mid, err)
                return
        elif method.startswith("notifications/"):
            self.error(mid, E_METHOD)  # a notification method sent with an id is not a request we know
            return
        with self.state_lock:
            if json.dumps(mid) in self.pending:
                dup = True     # an id already in flight: forwarding would overwrite it and drop one of the answers
            else:
                dup = False
                self.pending[json.dumps(mid)] = method
        if dup:
            self.error(None, E_ID)
            return
        self.to_server(msg)

    @staticmethod
    def _id_ok(mid):
        if isinstance(mid, bool):
            return False
        if isinstance(mid, int):
            return True
        return isinstance(mid, str) and not mid.startswith(OWN_ID_PREFIX)

    def check_call(self, params, missing=False):
        if missing or not isinstance(params, dict):
            return E_PARAMS
        name = params.get("name")
        args = params.get("arguments", {})
        if not isinstance(name, str) or not isinstance(args, dict):
            return E_PARAMS
        if name not in self.allowed:
            return E_TOOL
        if REFUSED_KEYS & set(args):
            return E_FILENAME
        if not set(args) <= self.args.get(name, frozenset()):
            return E_ARG
        opens_page = name in PAGE_TOOLS
        if name == "browser_navigate":
            if not url_ok(args.get("url")):
                return E_URL
        if name == "browser_tabs":
            if "url" in args and not url_ok(args["url"]):
                return E_URL
            opens_page = args.get("action") == "new"
        if name in UPLOAD_TOOLS and not self.paths_ok(args):
            return E_PATH
        if opens_page:
            with self.state_lock:
                if self.pages >= self.max_pages:
                    return E_PAGES
                self.pages += 1
        return None

    def paths_ok(self, args):
        for key in PATH_KEYS:
            if key not in args:
                continue
            vals = args[key] if isinstance(args[key], list) else [args[key]]
            for v in vals:
                # Absolute only (the schemas say so): the server resolves a relative path against its cwd
                # <task>/browser, not in/, so 'in/../config.json' would pass a check made against in/.
                if not isinstance(v, str) or not os.path.isabs(v):
                    return False
                real = os.path.realpath(v)
                if not real.startswith(self.in_dir + os.sep):
                    return False
        return True

    # server -> client
    def on_server(self, msg):
        method = msg.get("method")
        if method is not None:
            if "id" in msg:
                # roots/list, sampling/*, elicitation/*, anything else: answered here, never forwarded.
                self.error(msg.get("id"), E_SERVER_REQ, send=self.to_server)
                return
            if method not in SERVER_NOTIFICATIONS:
                return
            if method == "notifications/tools/list_changed":
                self.relist()
            self.to_client(msg)
            return
        key = json.dumps(msg.get("id"))
        if isinstance(msg.get("id"), str) and msg["id"].startswith(OWN_ID_PREFIX):
            self.on_relist(msg)
            return
        with self.state_lock:
            req = self.pending.pop(key, None)
        if req is None:
            return  # an answer to nothing the client asked: dropped
        if req == "tools/list" and "result" in msg:
            tools = msg["result"].get("tools") if isinstance(msg["result"], dict) else None
            if not isinstance(tools, list) or not all(isinstance(t, dict) for t in tools):
                self.error(msg.get("id"), E_LIST)
                return
            msg["result"]["tools"] = [t for t in tools if t.get("name") in self.allowed]
        self.to_client(msg)

    def relist(self):
        with self.state_lock:
            self.own_seq += 1
            mid = f"{OWN_ID_PREFIX}{self.own_seq}"
        self.to_server({"jsonrpc": "2.0", "id": mid, "method": "tools/list"})

    def on_relist(self, msg):
        # The allowlist is by name, so the client's own next tools/list is filtered as before; the re-list records
        # tools the server added that the pinned list does not know (a version drift the install gate should catch).
        tools = (msg.get("result") or {}).get("tools") if isinstance(msg.get("result"), dict) else None
        if not isinstance(tools, list):
            sys.stderr.write("mcp_filter: re-list after list_changed failed\n")
            return
        hidden = sorted(str(t.get("name")) for t in tools if isinstance(t, dict) and t.get("name") not in self.allowed)
        if hidden:
            sys.stderr.write(f"mcp_filter: hidden after list_changed: {', '.join(hidden)}\n")

    # loops
    def read_lines(self, stream, limit, side):
        while True:
            line = stream.readline(limit + 1)
            if not line:
                return
            if len(line) > limit:
                self.close(f"{side} line over {limit} bytes")
            if not line.strip():
                continue
            try:
                msg = json.loads(line, parse_constant=_no_constant)
            except ValueError:
                self.close(f"invalid JSON from {side}")
            if isinstance(msg, list):
                self.close(f"batch array from {side} (not supported)")
            if not isinstance(msg, dict):
                self.close(f"non-object message from {side}")
            yield msg

    def server_loop(self):
        try:
            for msg in self.read_lines(self.proc.stdout, self.server_line_max, "server"):
                self.on_server(msg)
        except (BrokenPipeError, OSError) as e:
            self.close(f"pipe error: {e}")
        self.close("server closed its output", code=self.proc.poll() or 0)

    def run(self, stdin=None):
        # Termination by signal takes the same path as any other close (browser included), via the self-pipe: a handler
        # calling close() directly would take state_lock, deadlocking if the signal lands while the main thread holds it.
        threading.Thread(target=self.signal_loop, daemon=True).start()
        for sig in (signal.SIGTERM, signal.SIGHUP):
            signal.signal(sig, self.on_signal)
        threading.Thread(target=self.server_loop, daemon=True).start()
        threading.Thread(target=self.poll_tree, daemon=True).start()
        try:
            for msg in self.read_lines(stdin or sys.stdin.buffer, self.client_line_max, "client"):
                self.on_client(msg)
        except (BrokenPipeError, OSError) as e:
            self.close(f"pipe error: {e}")
        # Client closed stdin: let the server finish, then make sure nothing of it survives. The tree is walked now,
        # while the server is still the parent of what it launched.
        # Stored, not passed: the server loop may be the one that closes (on the server's EOF).
        tree = self.descendants()
        with self.state_lock:
            self.known_tree.update(tree)
        try:
            self.proc.stdin.close()
        except OSError as e:
            sys.stderr.write(f"mcp_filter: closing server stdin: {e}\n")
        try:
            rc = self.proc.wait(timeout=EXIT_GRACE_S)
        except subprocess.TimeoutExpired:
            rc = 0
        self.close("client closed its input", code=rc if rc and rc > 0 else 0)


def _no_constant(name):
    # NaN / Infinity are not JSON; node's JSON.parse rejects them, so a forwarded line carrying one would never be
    # answered. Refused here instead, which closes the session like any invalid JSON.
    raise ValueError(f"non-JSON constant {name}")


def main(argv=None):
    p = argparse.ArgumentParser(prog="mcp_filter.py")
    p.add_argument("--task", required=True)
    # The PLAYWRIGHT_BROWSERS_PATH run-mcp.sh sets (<prefix>/browsers), written by install.sh config: only browser
    # executables under it can be killed by command-line ownership (see Filter.is_task_browser).
    p.add_argument("--browsers-path")
    p.add_argument("--grant", action="append", default=[], choices=sorted(GRANTS))
    p.add_argument("--max-pages", type=int, default=DEFAULT_MAX_PAGES)
    p.add_argument("--tools-file", default=TOOLS_FILE)
    p.add_argument("--args-file", default=ARGS_FILE)
    p.add_argument("--client-line-max", type=int, default=CLIENT_LINE_MAX)
    p.add_argument("--server-line-max", type=int, default=SERVER_LINE_MAX)
    p.add_argument("server", nargs=argparse.REMAINDER)
    a = p.parse_args(argv)
    cmd = a.server[1:] if a.server[:1] == ["--"] else a.server
    if not cmd:
        p.error("server command required after --")
    if a.max_pages < 0:
        p.error("--max-pages must be >= 0")
    if a.client_line_max < 1 or a.server_line_max < 1:
        p.error("line caps must be >= 1")
    pinned = pinned_tools(a.tools_file)
    Filter(cmd, a.task, allowed_tools(pinned, a.grant), a.max_pages, args=pinned_args(pinned, a.args_file),
           client_line_max=a.client_line_max, server_line_max=a.server_line_max, browsers_path=a.browsers_path).run()


if __name__ == "__main__":
    main()
